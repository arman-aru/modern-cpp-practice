#include <iostream>
using namespace std;

int main()
{
    for (int i = 2; i <= 5; i++)
    {
        for (int j = 1; j <= 10; j++)
        {
            int outPut = i * j;
            cout << i << " * " << j << "= " << outPut << "\n";
        }
        cout << "\n";
    }
    return 0;
}